// Generates lib/data/seed_photos.dart with a deterministic AI food-photo URL
// (Pollinations Flux, keyless) for every seed recipe. No network needed — the
// URLs are built from the recipe queries. Run locally:
//   dart run tool/build_ai_photos.dart
import 'dart:io';

import 'package:essensplan/data/seed_recipes.dart';
import 'package:essensplan/logic/ai_photo.dart';

void main() {
  final recipes = [...seedRecipes]..sort((a, b) => a.id.compareTo(b.id));
  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/build_ai_photos.dart — do not edit by hand.')
    ..writeln('// Maps a seed recipe id to a deterministic AI food-photo URL')
    ..writeln('// (Pollinations Flux model, keyless, no quota). Regenerate with:')
    ..writeln('//   dart run tool/build_ai_photos.dart')
    ..writeln('const Map<String, String> kSeedPhotos = {');
  for (final r in recipes) {
    buf.writeln("  '${r.id}': '${aiPhotoUrl(r)}',");
  }
  buf.writeln('};');
  File('lib/data/seed_photos.dart').writeAsStringSync(buf.toString());
  stderr.writeln('Wrote ${recipes.length} AI photo URLs to '
      'lib/data/seed_photos.dart');
}
