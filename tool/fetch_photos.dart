// One-off tool: fetch a real Spoonacular photo URL for every seed recipe and
// write them into lib/data/seed_photos.dart. Runs in CI (server-side, so no
// browser CORS) via the "Rezept-Fotos holen" workflow, which commits the
// result. Locally: `SPOONACULAR_KEY=xxx dart run tool/fetch_photos.dart`.
import 'dart:io';

import 'package:essensplan/data/seed_photos.dart';
import 'package:essensplan/data/seed_recipes.dart';
import 'package:essensplan/logic/spoonacular.dart';

Future<void> main() async {
  final raw = Platform.environment['SPOONACULAR_KEY'] ?? '';
  final key = raw.trim();
  // Safe diagnostics (no key value printed; a real Spoonacular key is 32 chars).
  stderr.writeln('SPOONACULAR_KEY raw length=${raw.length}, '
      'trimmed length=${key.length}');
  if (key.isEmpty) {
    stderr.writeln('SPOONACULAR_KEY not set');
    exit(1);
  }

  // Merge with what we already have, so a partial run (e.g. daily quota) never
  // drops previously fetched photos — we only fetch the ones still missing.
  final photos = <String, String>{...kSeedPhotos};
  final start = photos.length;
  for (final r in seedRecipes) {
    if (photos.containsKey(r.id)) continue;
    try {
      final url = await fetchSpoonacularImage(queryForRecipe(r), apiKey: key);
      if (url != null && url.isNotEmpty) {
        photos[r.id] = url;
        stderr.writeln('OK   ${r.id}  <-  "${queryForRecipe(r)}"  ->  $url');
      } else {
        stderr.writeln('MISS ${r.id}  (no result)');
      }
    } on SpoonacularException catch (e) {
      stderr.writeln('STOP ${r.id}  $e');
      // Quota reached or invalid key: fatal for the whole run — stop here and
      // keep everything fetched so far.
      if (e.message.contains('Tageslimit') || e.message.contains('ungültig')) {
        break;
      }
    } catch (e) {
      stderr.writeln('FAIL ${r.id}  $e');
    }
  }
  stderr.writeln('Added ${photos.length - start} new, '
      '${photos.length}/${seedRecipes.length} total.');

  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/fetch_photos.dart — do not edit by hand.')
    ..writeln('// Maps a seed recipe id to a real Spoonacular photo URL, '
        'fetched once in CI')
    ..writeln('// (server-side, no CORS) so the photos load everywhere without '
        'a runtime API')
    ..writeln('// call. Re-run the "Rezept-Fotos holen" workflow to refresh.')
    ..writeln('const Map<String, String> kSeedPhotos = {');
  final ids = photos.keys.toList()..sort();
  for (final id in ids) {
    buf.writeln("  '$id': '${photos[id]}',");
  }
  buf.writeln('};');

  File('lib/data/seed_photos.dart').writeAsStringSync(buf.toString());
  stderr.writeln('\nWrote ${photos.length}/${seedRecipes.length} photos to '
      'lib/data/seed_photos.dart');
}
