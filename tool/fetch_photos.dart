// One-off tool: fetch a real food photo URL for every seed recipe and write
// them into lib/data/seed_photos.dart. Runs in CI (server-side, so no browser
// CORS) via the "Rezept-Fotos holen" workflow, which commits the result.
//
// Prefers Pexels (professional, consistent food photography) when PEXELS_KEY
// is set, otherwise falls back to Spoonacular (SPOONACULAR_KEY). Locally:
//   PEXELS_KEY=xxx dart run tool/fetch_photos.dart
import 'dart:io';

import 'package:essensplan/data/seed_photos.dart';
import 'package:essensplan/data/seed_recipes.dart';
import 'package:essensplan/logic/pexels.dart';
import 'package:essensplan/logic/spoonacular.dart';

bool _isPexels(String url) => url.contains('pexels.com');

Future<void> main() async {
  final pexelsKey = (Platform.environment['PEXELS_KEY'] ?? '').trim();
  final spoonKey = (Platform.environment['SPOONACULAR_KEY'] ?? '').trim();
  final usePexels = pexelsKey.isNotEmpty;
  stderr.writeln('Source: ${usePexels ? 'Pexels' : 'Spoonacular'} '
      '(PEXELS_KEY len=${pexelsKey.length}, SPOONACULAR_KEY len=${spoonKey.length})');
  if (!usePexels && spoonKey.isEmpty) {
    stderr.writeln('No PEXELS_KEY or SPOONACULAR_KEY set');
    exit(1);
  }

  // Merge with what we already have from the SAME source, so a partial run
  // never drops photos; switching source starts fresh (ignores the other's
  // URLs, so e.g. ugly Spoonacular ones get replaced by Pexels).
  final photos = <String, String>{
    for (final e in kSeedPhotos.entries)
      if (_isPexels(e.value) == usePexels) e.key: e.value,
  };
  final start = photos.length;

  for (final r in seedRecipes) {
    if (photos.containsKey(r.id)) continue;
    final query = queryForRecipe(r);
    try {
      final url = usePexels
          ? await fetchPexelsImage(query, apiKey: pexelsKey)
          : await fetchSpoonacularImage(query, apiKey: spoonKey);
      if (url != null && url.isNotEmpty) {
        photos[r.id] = url;
        stderr.writeln('OK   ${r.id}  <-  "$query"  ->  $url');
      } else {
        stderr.writeln('MISS ${r.id}  (no result for "$query")');
      }
    } on PexelsException catch (e) {
      stderr.writeln('STOP ${r.id}  $e');
      if (e.message.contains('Limit') || e.message.contains('ungültig')) break;
    } on SpoonacularException catch (e) {
      stderr.writeln('STOP ${r.id}  $e');
      if (e.message.contains('Tageslimit') || e.message.contains('ungültig')) {
        break;
      }
    } catch (e) {
      stderr.writeln('FAIL ${r.id}  $e');
    }
  }
  stderr.writeln('Added ${photos.length - start} new, '
      '${photos.length}/${seedRecipes.length} total.');

  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/fetch_photos.dart — do not edit by hand.')
    ..writeln('// Maps a seed recipe id to a real food photo URL, fetched once '
        'in CI')
    ..writeln('// (server-side, no CORS) so the photos load everywhere without '
        'a runtime API')
    ..writeln('// call. Re-run the "Rezept-Fotos holen" workflow to refresh.')
    ..writeln('const Map<String, String> kSeedPhotos = {');
  final ids = photos.keys.toList()..sort();
  for (final id in ids) {
    buf.writeln("  '$id': '${photos[id]}',");
  }
  buf.writeln('};');

  File('lib/data/seed_photos.dart').writeAsStringSync(buf.toString());
  stderr.writeln('\nWrote ${photos.length}/${seedRecipes.length} photos to '
      'lib/data/seed_photos.dart');
}
