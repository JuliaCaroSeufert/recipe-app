// One-off batch: generate a styled AI food photo (Pollinations Flux) for every
// seed recipe, respecting the free rate limit (1 image / 45 s), download the
// JPEG into assets/recipe_photos/<id>.jpg, and regenerate lib/data/seed_photos
// .dart to map each recipe to its bundled asset. Runs in CI via the "KI-Fotos
// holen" workflow, which commits the images. Resumable: existing images are
// skipped, so a re-run only fills the gaps.
import 'dart:io';

import 'package:essensplan/data/seed_recipes.dart';
import 'package:essensplan/logic/ai_photo.dart';
import 'package:http/http.dart' as http;

Future<void> main() async {
  final dir = Directory('assets/recipe_photos')..createSync(recursive: true);
  final client = http.Client();

  for (final r in seedRecipes) {
    final path = 'assets/recipe_photos/${r.id}.jpg';
    final file = File(path);
    if (file.existsSync() && file.lengthSync() > 15000) {
      stderr.writeln('SKIP ${r.id} (already have ${file.lengthSync()}B)');
      continue;
    }
    try {
      final res = await client
          .get(Uri.parse(aiPhotoUrl(r)))
          .timeout(const Duration(seconds: 150));
      if (res.statusCode == 200 && res.bodyBytes.length > 15000) {
        file.writeAsBytesSync(res.bodyBytes);
        stderr.writeln('OK   ${r.id}  ${res.bodyBytes.length}B');
      } else {
        stderr.writeln(
            'BAD  ${r.id}  code=${res.statusCode} len=${res.bodyBytes.length}');
      }
    } catch (e) {
      stderr.writeln('FAIL ${r.id}  $e');
    }
    // Respect the free limit of one image per 45 seconds.
    await Future.delayed(const Duration(seconds: 50));
  }
  client.close();

  // Rebuild the map from whatever images exist (so partial runs still work).
  final ids = dir
      .listSync()
      .whereType<File>()
      .where((f) => f.path.endsWith('.jpg'))
      .map((f) => f.uri.pathSegments.last.replaceAll('.jpg', ''))
      .toList()
    ..sort();
  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/download_ai_photos.dart — do not edit by '
        'hand.')
    ..writeln('// Maps a seed recipe id to a bundled AI food photo asset '
        '(downloaded once in')
    ..writeln('// CI, respecting the image service\'s rate limit, then '
        'committed) so the photos')
    ..writeln('// load instantly and offline with no runtime image calls.')
    ..writeln('const Map<String, String> kSeedPhotos = {');
  for (final id in ids) {
    buf.writeln("  '$id': 'assets/recipe_photos/$id.jpg',");
  }
  buf.writeln('};');
  File('lib/data/seed_photos.dart').writeAsStringSync(buf.toString());
  stderr.writeln('\nWrote ${ids.length}/${seedRecipes.length} asset entries.');
}
